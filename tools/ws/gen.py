#!/usr/bin/env python3
"""Build src/english/ws-data.js for the 写作工坊 Writing Workshop.

    python3 tools/ws/gen.py PANEL_DIR

PANEL_DIR holds p{n}_{1..3}.png cut from the exam papers (they are NOT kept in the repo).
Each picture is encrypted with one random key (AES-GCM); that key is wrapped once per accepted
accepted answer (PBKDF2-SHA256, lower case; answers come from WW_NAMES, not from the repo).
The page asks for it, unwraps the key and keeps it on that iPad only. The data file holds no readable picture.
"""
import base64, io, json, os, sys
from PIL import Image
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.pbkdf2 import PBKDF2HMAC
from cryptography.hazmat.primitives import hashes
sys.path.insert(0, os.path.dirname(__file__))
from sets import SETS
# the accepted answers are not kept in the repo: WW_NAMES='a,b' (lower case) when you run this
NAMES = [n.strip().lower() for n in os.environ.get('WW_NAMES', '').split(',') if n.strip()]
assert NAMES, 'set WW_NAMES'

ITER = 150000
b64 = lambda b: base64.b64encode(b).decode()

def main(src, out):
    key = AESGCM.generate_key(256)
    wraps = []
    for n in NAMES:
        salt, iv = os.urandom(16), os.urandom(12)
        kek = PBKDF2HMAC(hashes.SHA256(), 32, salt, ITER).derive(n.encode())
        wraps.append(dict(s=b64(salt), c=b64(iv + AESGCM(kek).encrypt(iv, key, b'ww'))))
    sets = []
    for st in SETS:
        imgs = []
        for j in (1, 2, 3):
            im = Image.open(os.path.join(src, 'p%d_%d.png' % (st['n'], j))).convert('L')
            if im.width > 720:
                im = im.resize((720, round(im.height * 720 / im.width)), Image.LANCZOS)
            im = im.point(lambda v: 255 if v > 200 else v).quantize(4, dither=Image.Dither.NONE)   # line art: 4 greys is plenty
            bio = io.BytesIO(); im.save(bio, 'PNG', optimize=True)
            iv = os.urandom(12)
            imgs.append(b64(iv + AESGCM(key).encrypt(iv, bio.getvalue(), None)))
        sets.append(dict(id=st['id'], n=st['n'], src=st['src'], title=st['title'], words=st['words'],
            owners=[list(o) for o in st['owners']], phrases=[[t, p, o] for t, p, o in st['phrases']],
            sents=[[w, d, r, [list(x) for x in ds]] for w, d, r, ds in st['sents']], img=imgs))
    js = '/* 写作工坊 data — generated by tools/ws/gen.py; pictures are encrypted (key = his English name) */\nQB.WW=' + \
         json.dumps(dict(iter=ITER, wraps=wraps, sets=sets), ensure_ascii=False, separators=(',', ':')) + ';\n'
    with open(out, 'w', encoding='utf-8') as f:
        f.write(js)
    print('wrote', out, len(js) // 1024, 'KB')

if __name__ == '__main__':
    main(sys.argv[1], os.path.join(os.path.dirname(__file__), '..', '..', 'src', 'english', 'ws-data.js'))
