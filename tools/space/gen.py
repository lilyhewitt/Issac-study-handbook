# Space Mission data: edit data_p3.py / data_p4.py, then run  python3 tools/space/gen.py src/science/space-data.js  (from the repo root)
import json, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from data_p3 import P3
from data_p4 import P4
for p in P3: p.setdefault('seg', 'P3')
ALL = P3 + P4
n = 0
for p in ALL:
    assert p['meteor'] if p.get('meteor') else len(p['qs']) == 8, p['id']
    for q in p['qs']:
        n += 1
        if q['k'] == 'pr': assert q['parts']
out = '/* 太空探险 Space Mission questions — generated by gen.py from claude/太空探险_闯关题目设计.md. Do not edit by hand. */\nQB.SPACE=' + json.dumps(ALL, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(sys.argv[1], 'w').write(out)
print(len(ALL), 'planets', n, 'questions', len(out), 'bytes')
